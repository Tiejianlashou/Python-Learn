# while 循环 : 打印10遍"我是大帅哥~"
i = 0
while i < 10:
    print("我是大帅哥~")
    i += 1
else :#这里后面会讲到,这里有无else输出结果都一样,但是后面学到的如果循环有异常终止,else不会执行
    print("循环正常结束")


# 案例:计算1-100之间所有偶数的累加之和
i = 1 #循环开始数字
total = 0 #记录累加之和
while i <= 100:
    if i % 2 == 0: # 偶数
        total+=i
    i += 1
print (f"1-100之间的偶数的累加之和: {total}")
