# # # # # # # # # #  逻辑运算符 # # # # # # # # # #
# 案例1: 键盘输入一个整数,判断这个数字是否在 10-20 之间 -->在:True 不在:False
num = int(input("请输入你要判断的数 :"))
print(f"{num}在10-20之间:",10<=num and num<=20)# and连接的关系是并且的关系,两个条件同时成立(True),结果才是True;否则,就是False
print(f"{num}在10-20之间:", 10 <= num <= 20)

# 案例2: 键盘输入一个整数,判断这个数字是否不在 10-20 之间
num1 = int(input("请输入你要判断的数 :"))
print(f"{num1}不在10-20之间:",10>num1 or 20<num1)# or连接的条件,是或者的关系,只要其中有一个成立(True),结果就是True;全部不成立,结果才是False
