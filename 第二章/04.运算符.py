# 算术运算符 : + - * / // % **
print("10 + 4 =",10 + 4) # 加
print("10 - 4 =",10 - 4) # 减
print("10 * 4 =",10 * 4) # 乘
print("10 / 4 =",10 / 4) # 除
print("10 // 4 =",10 // 4) # 整除
print("10 % 4 =",10 % 4) # 取余/求模
print("10 ** 4 =",10 ** 4) # 幂指数,10的4次方

# 算术运算符的优先级 --> ** --> * / // % --> + -
print("0.1 + 10 / 4**2 = ",0.1 + 10 / 4 **2)

# 案例: 输入两个数 x 和 y ,计算x+y以及x-y的结果并输出
x = float(input("请输入第一个数 x :"))
y = float(input("请输入第二个数 y :"))

# 当输入x=0.5,y=0.4,算出 x-y =  0.09999999999999998-->精度损失
# 精度损失 :由于计算机底层是基于 二进制 进行数据的存储与处理,二进制是无法准确的表示所有的小数,因此涉及到浮点数的运算,可能会有损失精度
print("算出 x+y = ",x+y)
print("算出 x-y = ",x-y)

